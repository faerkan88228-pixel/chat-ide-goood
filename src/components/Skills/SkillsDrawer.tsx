/**
 * Skills RAG Database Drawer & Persistent Vector Manager
 */

import React, { useState } from 'react';
import { 
  Database, 
  Search, 
  Plus, 
  Trash2, 
  Sparkles, 
  X, 
  Play, 
  Copy, 
  Check, 
  Shield, 
  Code2, 
  Cpu,
  Download,
  Upload
} from 'lucide-react';
import { SkillItem } from '@/types';
import { skillsStore } from '@/services/skillsStore';
import { cn } from '@/lib/utils';

interface SkillsDrawerProps {
  isOpen: boolean;
  onClose: () => void;
  onSelectSkillPrompt?: (prompt: string) => void;
}

export const SkillsDrawer: React.FC<SkillsDrawerProps> = ({
  isOpen,
  onClose,
  onSelectSkillPrompt
}) => {
  const [skills, setSkills] = useState<SkillItem[]>(skillsStore.getAllSkills());
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<string>('all');
  const [isAddModalOpen, setIsAddModalOpen] = useState(false);
  const [copiedId, setCopiedId] = useState<string | null>(null);

  // New Skill Form State
  const [newSkillName, setNewSkillName] = useState('');
  const [newSkillDesc, setNewSkillDesc] = useState('');
  const [newSkillCategory, setNewSkillCategory] = useState<SkillItem['category']>('code');
  const [newSkillCode, setNewSkillCode] = useState('');
  const [newSkillTags, setNewSkillTags] = useState('');

  if (!isOpen) return null;

  const handleSearch = (q: string) => {
    setSearchQuery(q);
    if (!q.trim()) {
      setSkills(skillsStore.getAllSkills());
    } else {
      setSkills(skillsStore.searchSkills(q));
    }
  };

  const filteredSkills = selectedCategory === 'all' 
    ? skills 
    : skills.filter(s => s.category === selectedCategory);

  const handleDelete = (id: string) => {
    skillsStore.removeSkill(id);
    setSkills(skillsStore.getAllSkills());
  };

  const handleCreateSkill = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newSkillName.trim()) return;

    skillsStore.addSkill({
      name: newSkillName.trim(),
      description: newSkillDesc.trim() || 'Пользовательский агентный навык',
      triggerPattern: `(?:${newSkillName.toLowerCase().slice(0, 20)})`,
      category: newSkillCategory,
      language: 'typescript',
      codeTemplate: newSkillCode.trim() || '// Custom Skill Execution Logic\nexport function execute() { return true; }',
      confidenceBoost: 5.0,
      tags: newSkillTags.split(',').map(t => t.trim()).filter(Boolean),
      author: 'User',
      isAutoGenerated: false,
    });

    setSkills(skillsStore.getAllSkills());
    setIsAddModalOpen(false);
    setNewSkillName('');
    setNewSkillDesc('');
    setNewSkillCode('');
    setNewSkillTags('');
  };

  const handleCopyCode = (id: string, code: string) => {
    navigator.clipboard.writeText(code);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 1500);
  };

  const handleExportJson = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(skillsStore.getAllSkills(), null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `nexus_rag_skills_${Date.now()}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/75 backdrop-blur-md flex justify-end">
      <div className="w-full max-w-2xl h-full bg-zinc-950 border-l border-white/10 shadow-2xl flex flex-col">
        
        {/* Drawer Header */}
        <div className="p-5 border-b border-white/10 flex items-center justify-between gap-4 bg-zinc-900/80 shrink-0">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-purple-500/20 border border-purple-500/30 flex items-center justify-center text-purple-400">
              <Database size={20} />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-base font-bold text-white tracking-tight">База Навыков RAG (Persistent)</h2>
                <span className="px-2 py-0.5 rounded-full bg-purple-500/15 text-purple-300 font-mono text-[10px] font-bold">
                  {skills.length} векторов
                </span>
              </div>
              <p className="text-xs text-zinc-400">
                Пополняется автоматически через <code className="text-emerald-400 font-mono">/create_skills</code>
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleExportJson}
              className="p-2 rounded-xl bg-white/5 hover:bg-white/10 text-zinc-400 hover:text-white transition-all"
              title="Экспорт базы в JSON"
            >
              <Download size={16} />
            </button>
            <button
              onClick={onClose}
              className="p-2 rounded-xl bg-white/5 hover:bg-white/10 text-zinc-400 hover:text-white transition-all"
            >
              <X size={18} />
            </button>
          </div>
        </div>

        {/* Search and Categories Toolbar */}
        <div className="p-4 border-b border-white/5 bg-zinc-950/60 space-y-3 shrink-0">
          <div className="relative">
            <Search size={15} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-zinc-500" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => handleSearch(e.target.value)}
              placeholder="Поиск по триггерам, тегам, категориям или коду навыка..."
              className="w-full pl-9 pr-4 py-2.5 rounded-xl bg-zinc-900/90 border border-white/10 text-xs text-white placeholder:text-zinc-500 outline-none focus:border-purple-500 transition-all"
            />
          </div>

          <div className="flex items-center justify-between gap-2 overflow-x-auto pb-1">
            <div className="flex items-center gap-1.5 text-xs">
              {['all', 'code', 'security', 'architecture', 'rag'].map((cat) => (
                <button
                  key={cat}
                  onClick={() => setSelectedCategory(cat)}
                  className={cn(
                    "px-3 py-1 rounded-lg capitalize font-medium text-xs transition-all",
                    selectedCategory === cat 
                      ? "bg-purple-500/20 text-purple-300 border border-purple-500/40 font-semibold"
                      : "text-zinc-400 hover:bg-white/5"
                  )}
                >
                  {cat === 'all' ? 'Все' : cat}
                </button>
              ))}
            </div>

            <button
              onClick={() => setIsAddModalOpen(true)}
              className="flex items-center gap-1.5 px-3 py-1 rounded-lg bg-purple-600 hover:bg-purple-500 text-white font-bold text-xs shadow-md transition-all shrink-0"
            >
              <Plus size={13} />
              <span>Добавить Навык</span>
            </button>
          </div>
        </div>

        {/* Skills Cards List */}
        <div className="flex-1 overflow-y-auto p-4 space-y-3.5">
          {filteredSkills.map((skill) => (
            <div
              key={skill.id}
              className="p-4 rounded-2xl bg-zinc-900/70 border border-white/10 hover:border-purple-500/30 transition-all space-y-3 shadow-sm"
            >
              <div className="flex items-start justify-between gap-3">
                <div className="min-w-0">
                  <div className="flex items-center gap-2 flex-wrap">
                    <span className="font-bold text-xs text-white">{skill.name}</span>
                    {skill.isAutoGenerated && (
                      <span className="px-1.5 py-0.2 rounded bg-emerald-500/10 text-emerald-400 text-[9px] font-mono border border-emerald-500/20">
                        AUTO-RAG
                      </span>
                    )}
                    <span className="text-[10px] text-purple-400 font-mono font-medium">
                      +{skill.confidenceBoost}% Conf.
                    </span>
                  </div>
                  <p className="text-xs text-zinc-400 mt-1 leading-relaxed">{skill.description}</p>
                </div>

                <div className="flex items-center gap-1 shrink-0">
                  <button
                    onClick={() => handleCopyCode(skill.id, skill.codeTemplate)}
                    className="p-1.5 rounded-lg bg-white/5 hover:bg-white/10 text-zinc-400 hover:text-white transition-all"
                    title="Копировать код навыка"
                  >
                    {copiedId === skill.id ? <Check size={13} className="text-emerald-400" /> : <Copy size={13} />}
                  </button>

                  <button
                    onClick={() => handleDelete(skill.id)}
                    className="p-1.5 rounded-lg bg-white/5 hover:bg-rose-500/20 text-zinc-400 hover:text-rose-400 transition-all"
                    title="Удалить навык"
                  >
                    <Trash2 size={13} />
                  </button>
                </div>
              </div>

              {/* Tags and Trigger */}
              <div className="flex flex-wrap items-center gap-1.5 text-[10px] font-mono">
                <span className="text-zinc-500">Триггер:</span>
                <span className="px-1.5 py-0.5 rounded bg-zinc-950 text-zinc-300 border border-white/5">
                  {skill.triggerPattern}
                </span>
                {skill.tags.map((tag, tIdx) => (
                  <span key={tIdx} className="px-1.5 py-0.5 rounded bg-purple-500/10 text-purple-300">
                    #{tag}
                  </span>
                ))}
              </div>

              {/* Code Snippet Box */}
              <pre className="p-3 rounded-xl bg-zinc-950 text-[10px] font-mono text-zinc-300 overflow-x-auto max-h-32 border border-white/5 leading-relaxed">
                {skill.codeTemplate}
              </pre>

              {onSelectSkillPrompt && (
                <button
                  onClick={() => {
                    onSelectSkillPrompt(`Примени навык: ${skill.name}`);
                    onClose();
                  }}
                  className="w-full py-2 rounded-xl bg-purple-500/15 hover:bg-purple-500/25 border border-purple-500/30 text-purple-300 font-semibold text-xs transition-all flex items-center justify-center gap-1.5"
                >
                  <Sparkles size={13} />
                  <span>Использовать в диалоге Workspace</span>
                </button>
              )}
            </div>
          ))}
        </div>

      </div>

      {/* Add Custom Skill Modal */}
      {isAddModalOpen && (
        <div className="fixed inset-0 z-60 bg-black/80 backdrop-blur-md flex items-center justify-center p-4">
          <div className="w-full max-w-lg p-6 rounded-3xl bg-zinc-900 border border-white/15 shadow-2xl space-y-4">
            <h3 className="text-base font-bold text-white">Добавить Новый Навык в RAG Базу</h3>
            <form onSubmit={handleCreateSkill} className="space-y-3">
              <div>
                <label className="text-xs font-medium text-zinc-400 block mb-1">Название навыка</label>
                <input
                  type="text"
                  value={newSkillName}
                  onChange={(e) => setNewSkillName(e.target.value)}
                  placeholder="Например: Fast Tailwind Data Grid"
                  className="w-full px-3.5 py-2.5 rounded-xl bg-zinc-950 border border-white/10 text-xs text-white outline-none focus:border-purple-500"
                  required
                />
              </div>

              <div>
                <label className="text-xs font-medium text-zinc-400 block mb-1">Категория</label>
                <select
                  value={newSkillCategory}
                  onChange={(e) => setNewSkillCategory(e.target.value as any)}
                  className="w-full px-3.5 py-2.5 rounded-xl bg-zinc-950 border border-white/10 text-xs text-white outline-none focus:border-purple-500"
                >
                  <option value="code">Code</option>
                  <option value="security">Security</option>
                  <option value="architecture">Architecture</option>
                  <option value="rag">RAG</option>
                </select>
              </div>

              <div>
                <label className="text-xs font-medium text-zinc-400 block mb-1">Описание</label>
                <textarea
                  value={newSkillDesc}
                  onChange={(e) => setNewSkillDesc(e.target.value)}
                  placeholder="Краткое назначение и контекст применения..."
                  rows={2}
                  className="w-full px-3.5 py-2.5 rounded-xl bg-zinc-950 border border-white/10 text-xs text-white outline-none focus:border-purple-500 resize-none"
                />
              </div>

              <div>
                <label className="text-xs font-medium text-zinc-400 block mb-1">Шаблон Кода (TypeScript / Python / Rust)</label>
                <textarea
                  value={newSkillCode}
                  onChange={(e) => setNewSkillCode(e.target.value)}
                  placeholder="// Код функции навыка..."
                  rows={4}
                  className="w-full px-3.5 py-2.5 rounded-xl bg-zinc-950 border border-white/10 font-mono text-xs text-white outline-none focus:border-purple-500 resize-none"
                />
              </div>

              <div className="flex items-center justify-end gap-2 pt-2">
                <button
                  type="button"
                  onClick={() => setIsAddModalOpen(false)}
                  className="px-4 py-2 rounded-xl bg-white/5 hover:bg-white/10 text-xs text-zinc-300 font-semibold"
                >
                  Отмена
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 rounded-xl bg-purple-600 hover:bg-purple-500 text-white font-bold text-xs shadow-md"
                >
                  Сохранить
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

    </div>
  );
};
